function buildGeneratedWordPairs(): WordPair[] {
  return WORD_PAIR_BANKS.flatMap((bank) => {
    const civilianTerms = bank.terms.slice(0, 5);
    const spyTerms = bank.terms.slice(5, 10);
    return bank.contexts.flatMap((context) =>
      civilianTerms.flatMap((civilian) =>
        spyTerms.map((spy) => ({
          civilian: `${context}：${civilian}`,
          spy: `${context}：${spy}`,
        })),
      ),
    );
  });
}

function uniqueWordPairs(pairs: WordPair[]): WordPair[] {
  const seen = new Set<string>();
  return pairs.filter((pair) => {
    const key = `${pair.civilian}\u0000${pair.spy}`;
    if (seen.has(key)) return false;
    seen.add(key);
    return true;
  });
}

